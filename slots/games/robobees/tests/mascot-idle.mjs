import assert from 'node:assert/strict';
import {createSpinIdle} from '../dist/mascot/spin-idle.mjs';
const cycle=createSpinIdle();
assert.equal(cycle.rest(0),0);
cycle.setBusy(true,1);
assert.equal(cycle.rest(1),0);
assert.equal(cycle.rest(2),1);
assert.equal(cycle.rest(20),1);
cycle.setBusy(false,21);
assert.equal(cycle.rest(25.499),1);
const lifting=cycle.rest(25.8);
assert.ok(lifting>0&&lifting<1);
cycle.setBusy(true,25.8);
assert.equal(cycle.rest(25.8),lifting);
assert.equal(cycle.rest(26.2),1);
cycle.setBusy(false,27);
cycle.setBusy(true,27.2);
assert.equal(cycle.rest(32),1);
cycle.setBusy(false,33);
assert.equal(cycle.rest(38.2),0);
console.log('Idle, busy, chained spins, delayed takeoff and interrupted takeoff pass.');
