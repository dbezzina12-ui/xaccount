#!/usr/bin/env node
// Writes games/zombify/MATH.md and games/zombify/math/summary.json: Zombify v125's
// math, measured exactly from its outcome catalogs (tools/math/zombify.js).
// Zombify was imported unchanged (D-004); this only measures it. Engine replay
// and session checks come from games/zombify/math/verify.json when present
// (node tools/math/zombify-verify.mjs).
//
//   node tools/math/zombify-report.mjs

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { CAP, ENTRY, TIERS, MYSTERY, EDGES, loadCatalogs, modes, stats } from './zombify.js';

const dir = new URL('../../games/zombify/', import.meta.url);
const catalogs = await loadCatalogs();
const all = modes(catalogs).map((m) => ({ ...m, s: stats(m) }));
const verify = existsSync(new URL('math/verify.json', dir)) ? JSON.parse(readFileSync(new URL('math/verify.json', dir), 'utf8')) : null;
const manifest = JSON.parse(readFileSync(new URL('import-manifest.json', dir), 'utf8'));
const pin = (f) => manifest.files.find((x) => x.path === f)?.sha256;

const pct = (x, d = 2) => `${(x * 100).toFixed(d)}%`;
const x = (v, d = 2) => `${Number(v).toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d })}x`;
const oneIn = (p) => (p > 0 ? `1 in ${Math.round(1 / p).toLocaleString('en-US')}` : 'never');
const vol = (sd) => (sd < 5 ? 'Low' : sd < 10 ? 'Medium' : sd < 15 ? 'High' : 'Very high');
const mean = (d) => [...d].reduce((s, [v, p]) => s + v * p, 0) / 100;
const band = (i) => (i === 0 ? 'No win' : i === 1 ? `Under ${EDGES[1]}x` : EDGES[i] === Infinity ? `${EDGES[i - 1]}x+` : `${EDGES[i - 1]}x to under ${EDGES[i]}x`);
// Common chances read best as a percentage, rare ones as odds.
const chance = (p) => (p === 0 ? '—' : p >= 0.01 ? pct(p) : oneIn(p));

const base = all.find((m) => m.kind === 'base'), enhanced = all.find((m) => m.kind === 'enhanced');
const split = (m) => ({ noBonus: ((1 - m.entry) * mean(m.parts.noBonus)) / m.cost, bonus: (m.entry * mean(m.parts.bonus)) / m.cost });
const lines = [];
const row = (...cells) => lines.push(`| ${cells.join(' | ')} |`);

lines.push('# Zombify: math sheet', '',
  '> Generated by `node tools/math/zombify-report.mjs` and owned by Claude. Do not edit by hand. Zombify was imported from v125 with its math unchanged (D-004). On 2026-10-28 Dylan asked for Hidden bonuses to pay at least 1,000x and for Second Life to start with up to four zombies; `tools/math/zombify-rebalance.mjs` rebuilt both catalogs from the v125 ones. Figures are exact: they come straight from the outcome catalogs the game draws from.', '',
  '## Headline numbers', '');
row('Mode', 'Cost', 'RTP', 'Hit rate', 'Returns at least the cost', 'SD per cost', 'Volatility', 'Max win', `Reaches the ${x(CAP / 100, 0)} cap`);
row('---', '---', '---', '---', '---', '---', '---', '---', '---');
for (const m of all) row(m.title, x(m.cost, m.cost % 1 ? 1 : 0), `**${pct(m.s.rtp, 4)}**`, pct(m.s.hit), pct(m.s.breakEven), m.s.sd.toFixed(2), vol(m.s.sd), x(m.s.maxBet), oneIn(m.s.capped));
lines.push('', 'Costs, wins and the cap are in multiples of the base bet. "SD per cost" is the standard deviation of one round\'s return divided by its cost; volatility uses the same bands as Game 001.', '');

lines.push('## How the math works', '',
  '- Every round draws an outcome from a weighted catalog (`games/zombify/runtime/outcomes.js`, `feature-outcomes.js`) and replays its seed to animate a result whose payout is already known. Ticket draws use rejection sampling, so there is no modulo bias.',
  `- **Base spin:** a bonus starts 1 in ${Math.round(1 / ENTRY.base)}. **Enhanced spin** (${enhanced.cost}x cost): 1 in ${Math.round(1 / ENTRY.enhanced)}. A started bonus is ${Object.entries(TIERS).map(([t, p]) => `${pct(p, 0)} ${t}`).join(', ')}. It pays the trigger spin plus the bonus, capped at ${x(CAP / 100, 0)}.`,
  `- **Buys** skip the trigger spin: Outbreak, Super Outbreak, or Mystery (${Object.entries(MYSTERY).map(([t, p]) => `${pct(p, 0)} ${t}`).join(', ')}). **Second Life** is its own feature with its own catalog.`,
  '- The engine checks every round against its catalog value before crediting, and refuses the round on any mismatch.', '');

lines.push('## Where the base-spin RTP comes from', '');
row('Part', 'Base spin', 'Enhanced spin'); row('---', '---', '---');
const [sb, se] = [split(base), split(enhanced)];
row('Spins without a bonus', pct(sb.noBonus, 3), pct(se.noBonus, 3));
row('Bonuses (trigger spin + bonus)', pct(sb.bonus, 3), pct(se.bonus, 3));
for (const t of Object.keys(TIERS)) row(`  of which ${t}`, pct((base.entry * TIERS[t] * mean(base.parts.natural[t])) / base.cost, 3), pct((enhanced.entry * TIERS[t] * mean(enhanced.parts.natural[t])) / enhanced.cost, 3));
row('**Total**', `**${pct(base.s.rtp, 3)}**`, `**${pct(enhanced.s.rtp, 3)}**`);
lines.push('');

lines.push('## Average bonus value', '');
row('Bonus', 'Free spins', 'Average win from a spin trigger', 'Average win as a buy'); row('---', '---', '---', '---');
const pools = Object.fromEntries(Object.keys(TIERS).map((t) => [t, all.find((m) => m.kind === { regular: 'buy_outbreak', super: 'buy_super' }[t])]));
const tierMean = (t) => { const p = catalogs.data.pools[t]; let prev = 0, s = 0; for (const e of p.entries) { s += (e[1] - prev) * e[2]; prev = e[1]; } return s / p.total / 100; };
for (const [t, spins] of [['regular', 8], ['super', 10], ['hidden', 10]]) row({ regular: 'Outbreak', super: 'Super Outbreak', hidden: 'Hidden Outbreak' }[t], spins, x(mean(base.parts.natural[t])), pools[t] ? x(mean(pools[t].dist)) : `${x(tierMean(t))} (Mystery only)`);
lines.push('');

// Second Life by starting zombies (the first event of a replayed round says how many).
const { seeded } = await import('../../games/zombify/runtime/math.js');
const { makeFeatureRound } = await import('../../games/zombify/runtime/feature-spin.js');
const { FEATURE_SPIN } = await import('../../games/zombify/runtime/config.js');
const life = new Map(), hearts = [0, 0, 0];
{ let prev = 0; for (const e of catalogs.feature.pool.entries) { const w = (e[1] - prev) / catalogs.feature.pool.total; prev = e[1]; const z = makeFeatureRound({ rng: seeded(e[0]) }).events[0].zombies, c = life.get(z) ?? { p: 0, pay: 0, respin: 0 }; c.p += w; c.pay += w * e[2]; if (e[3]) c.respin += w; life.set(z, c); hearts[Math.min(2, e[3])] += w; } }
lines.push('## Second Life', '', `Each round starts with 2, 3 or 4 guaranteed zombies, on different reels. A heart in a zombie's path gives a respin; every heart after the first also brings one more zombie onto a free reel, up to ${FEATURE_SPIN.maxZombies}.`, '');
row('Starting zombies', 'Chance', 'Average win', 'At least one respin'); row('---', '---', '---', '---');
for (const [z, c] of [...life].sort((a, b) => a[0] - b[0])) row(z, pct(c.p), x(c.pay / c.p / 100), pct(c.respin / c.p));
lines.push('', `Hearts collected: none ${pct(hearts[0])}, one ${pct(hearts[1])}, two or more ${pct(hearts[2])}.`, '');

// The shop's free previews (S-28). They never pay into credits (session.js).
const { makePaidRound, CATALOG_PREVIEWS } = await import('../../games/zombify/runtime/outcome-model.js');
const capChance = (d) => [...d].reduce((s, [v, p]) => s + (v >= CAP ? p : 0), 0);
lines.push('## Free previews', '', 'Previews cost nothing and never pay into credits. Super and Hidden previews play a real bonus each time: a trigger spin and a bonus drawn from the catalogs exactly as a natural bonus is, so they pay what that bonus really pays. Outbreak and Second Life previews replay one fixed demonstration round.', '');
row('Preview', 'Plays', 'Average win', `Reaches the ${x(CAP / 100, 0)} cap`); row('---', '---', '---', '---');
for (const [kind, t] of Object.entries(CATALOG_PREVIEWS)) row({ super: 'Super Outbreak', hidden: 'Hidden Outbreak' }[t], `a real ${t} bonus, drawn afresh`, x(mean(base.parts.natural[t])), oneIn(capChance(base.parts.natural[t])));
for (const [kind, title, seed] of [['outbreak', 'Outbreak', 3], ['preview_feature', 'Second Life', 3013]]) {
  const total = makePaidRound({ kind, rng: seeded(seed) }).total;
  row(title, `the same demonstration round (seed ${seed})`, `${x(total / 100)} every time`, total >= CAP ? 'every time' : 'never');
}
lines.push('');

lines.push('## Win distribution', '', 'Chance of a round paying in each band, in multiples of **that mode\'s cost** ("Under 1x" pays something, but less than the cost).', '');
row('Win', ...all.map((m) => m.title)); row('---', ...all.map(() => '---'));
EDGES.forEach((_, i) => row(band(i), ...all.map((m) => chance(m.s.bands[i]))));
lines.push('');

lines.push('## Verification', '');
if (verify) {
  const checked = Object.values(verify.replay).reduce((n, r) => n + r.checked, 0), bad = Object.values(verify.replay).reduce((n, r) => n + r.mismatches, 0);
  lines.push(`From \`node tools/math/zombify-verify.mjs\` (${verify.generated.slice(0, 10)}, ${verify.seconds}s). **${checked.toLocaleString('en-US')} catalog outcomes replayed through the real engine, ${bad} mismatches.**`, '');
  row('Replayed', 'Outcomes', 'Mismatches'); row('---', '---', '---');
  for (const [k, r] of Object.entries(verify.replay)) row(k, r.checked.toLocaleString('en-US'), r.mismatches);
  lines.push('', 'Rounds played through the real session code (`createSession().begin/finish`), seeded. The heavy tail makes sample RTP noisy; the exact figures above are authoritative.', '');
  row('Mode', 'Rounds', 'Sample RTP (95% CI)', 'Exact RTP', 'Sample hit rate', 'Exact hit rate', 'Errors'); row('---', '---', '---', '---', '---', '---', '---');
  for (const m of all) { const r = verify.sessions[m.kind]; if (r) row(m.title, r.rounds.toLocaleString('en-US'), `${pct(r.rtp, 3)} ± ${pct(r.ci95, 3)}`, pct(r.exactRtp, 3), pct(r.hitRate), pct(r.exactHit), r.errors); }
} else lines.push('Run `node tools/math/zombify-verify.mjs` to replay the catalogs through the engine.');
lines.push('', '## Catalog identity', '',
  `- \`outcomes.js\`: version \`${catalogs.data.version}\`, source hash \`${catalogs.data.sourceHash}\`, file SHA-256 \`${pin('outcomes.js')}\``,
  `- \`feature-outcomes.js\`: version \`${catalogs.feature.version}\`, source hash \`${catalogs.feature.sourceHash}\`, file SHA-256 \`${pin('feature-outcomes.js')}\``,
  '- Both are built by `node tools/math/zombify-rebalance.mjs` from the hash-verified v125 catalogs, tracked in the repository, and hash-pinned in `games/zombify/import-manifest.json` (`npm run studio:prepare` verifies them).', '');

writeFileSync(new URL('MATH.md', dir), lines.join('\n'));
mkdirSync(new URL('math/', dir), { recursive: true });
const summary = Object.fromEntries(all.map((m) => [m.kind, { title: m.title, cost: m.cost, ...m.s, maxBet: m.s.maxBet, bands: Object.fromEntries(m.s.bands.map((p, i) => [band(i), p])) }]));
writeFileSync(new URL('math/summary.json', dir), JSON.stringify({ modelVersion: catalogs.data.version, featureVersion: catalogs.feature.version, cap: CAP / 100, modes: summary, baseSplit: sb, enhancedSplit: se }, null, 1) + '\n');
console.log('Wrote games/zombify/MATH.md and games/zombify/math/summary.json');
