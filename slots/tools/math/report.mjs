#!/usr/bin/env node
// Writes games/<id>/MATH.md: the game's PAR sheet. Exact figures come from
// exact.js; capped RTP, volatility and the win distribution come from the
// saved simulator runs in games/<id>/math/sim-*.json.
//
//   node tools/math/report.mjs games/game-001

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { compileModel } from '../../engine/core/model.js';
import { exactStats, reelMarginals } from './exact.js';

const dir = process.argv[2] ?? 'games/game-001';
const json = JSON.parse(readFileSync(join(dir, 'model.json'), 'utf8'));
const m = compileModel(json);
const ex = exactStats(m);
const load = (f) => (existsSync(join(dir, 'math', f)) ? JSON.parse(readFileSync(join(dir, 'math', f), 'utf8')) : null);
const simBase = load('sim-base.json');
const simBuy = load('sim-buy.json');

const pct = (x, d = 2) => `${(x * 100).toFixed(d)}%`;
const x = (v, d = 2) => `${Number(v).toFixed(d)}x`;
const oneIn = (v) => (Number.isFinite(v) ? `1 in ${Math.round(v).toLocaleString('en-US')}` : 'not observed');
const vol = (sd) => (sd < 5 ? 'Low' : sd < 10 ? 'Medium' : sd < 15 ? 'High' : 'Very high');
const nL = m.nLines;
// Smallest run that pays anything; paytable columns start here.
const minK = Math.min(...Object.values(json.pays).flatMap((t) => Object.keys(t).filter((k) => t[k] > 0).map(Number)));
const counts = Array.from({ length: m.reels - minK + 1 }, (_, i) => minK + i);
const hasMult = m.multValues.some((v) => v > 1);
const hasRetrigger = m.retrigger.some((v) => v > 0);

const L = [];
L.push(`# ${json.title ?? json.id}: math sheet`);
L.push('');
L.push('> Generated by `node tools/math/report.mjs` and owned by Claude. Do not edit by hand; change `model.json` / `math/reel-design.json` and regenerate.');
L.push('');
L.push('## Headline numbers');
L.push('');
L.push('| Metric | Value | Source |');
L.push('|---|---|---|');
L.push(`| RTP (theoretical, before max-win cap) | **${pct(ex.rtp, 3)}** | exact |`);
if (simBase?.capCost !== undefined) {
  L.push(`| RTP the ${json.maxWinX.toLocaleString('en-US')}x cap removes | ${pct(simBase.capCost, 4)} | sim, paired replay of every capped round |`);
  L.push(`| **RTP (as played, with cap)** | **${pct(ex.rtp - simBase.capCost, 3)}** | exact − cap cost |`);
}
if (simBase) L.push(`| RTP, raw simulation | ${pct(simBase.rtp, 3)} ± ${pct(simBase.rtpCI95, 3)} | sim, ${simBase.rounds.toLocaleString('en-US')} rounds, 95% CI (cross-check) |`);
L.push(`| Base game lines | ${pct(ex.rtpLines)} | exact |`);
L.push(`| Scatter pays | ${pct(ex.rtpScatter)} | exact |`);
L.push(`| Free spins feature | ${pct(ex.rtpFeature)} | exact |`);
L.push(`| Hit rate (any win, base spin) | ${ex.baseHitRate === null ? 'n/a' : pct(ex.baseHitRate)} | exact |`);
L.push(`| Free spins trigger | ${oneIn(ex.triggerOneIn)} spins | exact |`);
for (const a of Object.values(ex.awards)) L.push(`| Average feature win (${a.spins} spins) | ${x(a.avgWinX)} | exact |`);
if (ex.bonusBuy) {
  const capped = simBuy?.capCost !== undefined ? ex.bonusBuy.rtp - simBuy.capCost : null;
  L.push(`| Bonus buy (${ex.bonusBuy.priceX}x for ${ex.bonusBuy.spins} spins) RTP | **${pct(capped ?? ex.bonusBuy.rtp, 3)}**${capped !== null ? ` (uncapped ${pct(ex.bonusBuy.rtp, 3)}; raw sim ${pct(simBuy.rtp, 3)} ± ${pct(simBuy.rtpCI95, 3)})` : ''} | exact${simBuy ? ' + sim' : ''} |`);
  if (simBuy) L.push(`| Bonus buy reaches max win | ${oneIn(simBuy.capOneIn)} buys | sim |`);
}
if (simBase) {
  L.push(`| Volatility (SD per spin) | ${x(simBase.sd)} → **${vol(simBase.sd)}** | sim |`);
  L.push(`| Max win cap | ${json.maxWinX.toLocaleString('en-US')}x bet, reached ${oneIn(simBase.capOneIn)} spins | sim |`);
  L.push(`| Biggest win seen in sim | ${x(simBase.maxWinX)} | sim |`);
}
L.push('');

L.push('## Rules the math assumes');
L.push('');
L.push(`- ${m.reels} reels × ${m.rows} rows, ${nL} fixed paylines, pays left to right from reel 1. Total bet = ${nL} × line bet.`);
if (m.WILD >= 0) L.push(`- **${m.symbols[m.WILD]}** (wild) lands on reels ${[...m.wildReels].map((r) => r + 1).join(', ')} only and substitutes for every symbol except the scatter. It has no pay of its own.`);
L.push(`- **${m.symbols[m.SCATTER]}** (scatter) pays anywhere and awards free spins: ${Object.entries(json.scatter.awards).map(([k, v]) => `${k} → ${v} spins`).join(', ')}. At most one per reel.`);
L.push(`- Free spins use their own reel set.${hasMult ? ` Every wild carries a multiplier (${m.multValues.map((v, i) => `x${v} ${pct(m.multWeights[i] / m.multTotal, 0)}`).join(', ')}; average x${ex.expectedMultiplier.toFixed(2)}). Multipliers of wilds in the same winning line **multiply**.` : ' No multipliers.'}`);
L.push(`- ${hasRetrigger ? `Retriggers: ${Object.entries(json.freeSpins.retrigger).map(([k, v]) => `${k} scatters → +${v}`).join(', ')}.` : 'No retriggers.'}`);
L.push(`- The whole round (base spin + its free spins) is capped at ${json.maxWinX.toLocaleString('en-US')}x bet; reaching it ends the round.`);
L.push('');

L.push('## Paytable (x total bet)');
L.push('');
L.push(`| Symbol | ${counts.map((n) => `${n} of a kind`).join(' | ')} |`);
L.push(`|---|${'---|'.repeat(counts.length)}`);
for (const s of Object.keys(json.pays)) {
  L.push(`| ${s} | ${counts.map((n) => x((json.pays[s][n] ?? 0) / nL, 2)).join(' | ')} |`);
}
L.push(`| ${m.symbols[m.SCATTER]} (anywhere) | ${counts.map((n) => x(json.scatter.pays?.[n] ?? 0, 0)).join(' | ')} |`);
L.push('');

L.push('## Where the base-game return comes from');
L.push('');
L.push(`| Symbol | ${counts.map((n) => `${n}oak`).join(' | ')} | Total |`);
L.push(`|---|${'---|'.repeat(counts.length + 1)}`);
for (const [s, arr] of Object.entries(ex.baseBySymbol)) {
  const cells = arr.slice(minK).map((v) => pct(v));
  L.push(`| ${s} | ${cells.join(' | ')} | ${pct(arr.reduce((a, b) => a + b, 0))} |`);
}
L.push('');

L.push('## Scatter odds');
L.push('');
L.push('| Scatters | Base game | During free spins |');
L.push('|---|---|---|');
for (let k = 1; k <= m.reels; k++) if (m.scatterAward[k] > 0 || m.scatterPayX[k] > 0) L.push(`| ${k} | ${oneIn(1 / ex.scatterDist.base[k])} | ${oneIn(1 / ex.scatterDist.free[k])} |`);
L.push('');
L.push(`Free spins: average win per spin ${x(ex.freeSpin.avgWinX)}, retrigger chance per spin ${pct(ex.freeSpin.retriggerProb, 3)}, expected extra spins per spin ${ex.freeSpin.retriggerSpinsPerSpin.toFixed(4)}.`);
L.push('');

if (simBase) {
  L.push('## Win distribution (per base spin, from sim)');
  L.push('');
  L.push('| Win (x bet) | Probability | 1 in |');
  L.push('|---|---|---|');
  const n = simBase.rounds;
  const B = simBase.buckets;
  const label = (i) => (i === 0 ? 'no win' : i < B.length ? `${B[i - 1]}x – ${B[i]}x` : i === B.length ? `${B[B.length - 1]}x +` : `max win (${json.maxWinX}x)`);
  simBase.hist.forEach((c, i) => {
    if (i === 1) L.push(`| under 1x (win < bet) | ${pct(c / n, 3)} | ${oneIn(n / c)} |`);
    else if (i === 0) L.push(`| no win | ${pct(c / n, 3)} | |`);
    else L.push(`| ${label(i)} | ${pct(c / n, i > 7 ? 5 : 3)} | ${c ? oneIn(n / c) : 'not observed'} |`);
  });
  L.push('');
}
if (simBuy) {
  L.push(`## Bonus buy distribution (${simBuy.rounds.toLocaleString('en-US')} buys, x price)`);
  L.push('');
  L.push('| Return (x price) | Probability |');
  L.push('|---|---|');
  const B = simBuy.buckets;
  simBuy.hist.forEach((c, i) => {
    const label = i === 0 ? 'nothing' : i < B.length ? `${B[i - 1]}x – ${B[i]}x` : i === B.length ? `${B[B.length - 1]}x +` : 'max win';
    L.push(`| ${label} | ${pct(c / simBuy.rounds, 3)} |`);
  });
  L.push('');
  L.push(`Average bought feature: ${x(simBuy.feature.avgWinX)} bet (SD ${x(simBuy.feature.sdX, 1)}).`);
  L.push('');
}

L.push('## Reel strips');
L.push('');
L.push('Symbol counts (strip length in brackets):');
L.push('');
for (const set of ['base', 'free']) {
  const marg = reelMarginals(m, set);
  L.push(`**${set}**`);
  L.push('');
  L.push(`| Symbol | ${m.strips[set].map((s, i) => `Reel ${i + 1} (${s.length})`).join(' | ')} |`);
  L.push(`|---|${'---|'.repeat(m.reels)}`);
  for (let s = 0; s < m.nSym; s++) {
    L.push(`| ${m.symbols[s]} | ${marg.map((p, i) => Math.round(p[s] * m.strips[set][i].length)).join(' | ')} |`);
  }
  L.push('');
}

L.push('## Reproduce');
L.push('');
L.push('```sh');
L.push(`node tools/math/build-reels.mjs ${dir}          # strips from math/reel-design.json`);
L.push(`node tools/math/sim.mjs ${dir}/model.json --rounds 1e9 --json ${dir}/math/sim-base.json`);
L.push(`node tools/math/sim.mjs ${dir}/model.json --buy --rounds 5e7 --json ${dir}/math/sim-buy.json`);
L.push(`node tools/math/report.mjs ${dir}               # rewrites this file`);
L.push('```');
L.push('');
if (simBase) L.push(`Sim seeds: base ${simBase.seed}${simBuy ? `, buy ${simBuy.seed}` : ''}. Same seed + same model = identical numbers.`);
L.push('');

writeFileSync(join(dir, 'MATH.md'), L.join('\n'));

// Headline figures for the in-game info panel.
const summary = {
  rtp: ex.rtp - (simBase?.capCost ?? 0),
  rtpBonusBuy: ex.bonusBuy ? ex.bonusBuy.rtp - (simBuy?.capCost ?? 0) : null,
  hitRate: ex.baseHitRate,
  featureOneIn: ex.triggerOneIn,
  volatility: simBase ? vol(simBase.sd) : null,
  maxWinX: json.maxWinX,
  maxWinOneIn: simBase?.capOneIn ?? null,
};
mkdirSync(join(dir, 'math'), { recursive: true });
writeFileSync(join(dir, 'math/summary.json'), JSON.stringify(summary, null, 2) + '\n');
console.log(`wrote ${join(dir, 'MATH.md')}  (exact RTP ${pct(ex.rtp, 3)})`);
