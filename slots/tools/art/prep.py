#!/usr/bin/env python3
"""Check (and optionally optimize) a game's art drop against ART_SPEC.md.

  python3 tools/art/prep.py games/game-001             # check only
  python3 tools/art/prep.py games/game-001 --optimize  # also shrink for the web;
                                                        # originals move to art/source/

Writes games/<id>/art/REPORT.md. Needs Pillow (pip install pillow).
"""
import json
import shutil
import sys
from pathlib import Path

from PIL import Image

# Mirrors engine/client/assets.js ART_FILES.
SCENES = [
    ("bg-base.png", "landscape", False),
    ("bg-base-portrait.png", "portrait", False),
    ("bg-free.png", "landscape", False),
    ("bg-free-portrait.png", "portrait", False),
    ("logo.png", "wordmark", True),
    ("banner-free-spins.png", "wordmark", True),
    ("banner-big-win.png", "wordmark", True),
    ("banner-mega-win.png", "wordmark", True),
    ("banner-epic-win.png", "wordmark", True),
    ("banner-max-win.png", "wordmark", True),
    ("fx-coin.png", "square", True),
]
WEB_MAX = {"square": 512, "landscape": 1536, "portrait": 1536, "wordmark": 1536}


def alpha_info(im):
    if im.mode not in ("RGBA", "LA") and "transparency" not in im.info:
        return False, None
    a = im.convert("RGBA").getchannel("A")
    w, h = a.size
    corners = [a.getpixel((0, 0)), a.getpixel((w - 1, 0)), a.getpixel((0, h - 1)), a.getpixel((w - 1, h - 1))]
    bbox = a.point(lambda v: 255 if v > 12 else 0).getbbox()
    fill = None
    if bbox:
        fill = ((bbox[2] - bbox[0]) * (bbox[3] - bbox[1])) / (w * h)
    return min(corners) < 200, fill


def check(path, shape, needs_alpha):
    if not path.exists():
        return "missing", ""
    with Image.open(path) as im:
        w, h = im.size
        notes = [f"{w}×{h}"]
        status = "ok"
        ratio = w / h
        want = {"square": 1, "landscape": 1.5, "portrait": 2 / 3}.get(shape)
        if want and abs(ratio - want) > 0.04:
            status = "warn"
            notes.append(f"aspect {ratio:.2f}, expected {want:.2f}")
        transparent, fill = alpha_info(im)
        if needs_alpha and not transparent:
            status = "fail"
            notes.append("needs a transparent background")
        if needs_alpha and fill is not None and shape == "square" and fill < 0.35:
            notes.append(f"subject fills only {fill:.0%} of the canvas (fine, engine trims)")
        if not needs_alpha and transparent:
            notes.append("has transparency (backgrounds should be opaque)")
        return status, ", ".join(notes)


def optimize(art, rel, shape):
    src = art / rel
    keep = art / "source" / rel
    if not keep.exists():
        keep.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, keep)
    with Image.open(keep) as im:
        im = im.convert("RGBA") if im.mode in ("RGBA", "LA", "P") else im.convert("RGB")
        im.thumbnail((WEB_MAX[shape], WEB_MAX[shape]), Image.LANCZOS)
        im.save(src, optimize=True)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    game = Path(sys.argv[1])
    do_opt = "--optimize" in sys.argv
    model = json.loads((game / "model.json").read_text())
    art = game / "art"
    items = [(f"symbols/{s}.png", "square", True) for s in model["symbols"]] + SCENES
    rows = []
    for rel, shape, needs_alpha in items:
        status, notes = check(art / rel, shape, needs_alpha)
        if do_opt and status in ("ok", "warn"):
            optimize(art, rel, shape)
        rows.append((rel, status, notes))
    icon = {"ok": "✅", "warn": "⚠️", "fail": "❌", "missing": "·"}
    have = sum(1 for r in rows if r[1] in ("ok", "warn"))
    lines = [
        f"# Art report: {game.name}",
        "",
        f"{have} of {len(rows)} files delivered. Generated by `python3 tools/art/prep.py {game}`.",
        "",
        "| File | Status | Notes |",
        "|---|---|---|",
    ]
    lines += [f"| `{rel}` | {icon[st]} {st} | {notes} |" for rel, st, notes in rows]
    (art / "REPORT.md").write_text("\n".join(lines) + "\n")
    for rel, st, notes in rows:
        print(f"{icon[st]} {rel:32} {notes}")
    print(f"\n{have}/{len(rows)} delivered → {art / 'REPORT.md'}")
    if any(r[1] == "fail" for r in rows):
        sys.exit(1)


if __name__ == "__main__":
    main()
